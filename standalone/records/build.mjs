// apply every patch in the variant; refuse 0 or 2+ matches; recognise already-applied; refuse foreign markers
export function patchModule(mod, variant) {
  let cur = mod;
  const added = {};
  const ctx = {};
  for (const p of PATCHES) {
    const marks = countStr(cur, p.marker);
    const ms = countRe(p.anchor, cur);
    if (!p.applies(variant)) {
      if (marks !== 0) fail(`PATCH ${p.id} is already present in the input module but not part of variant (level ${variant.level}, fm19 ${variant.fm19}, fm21 ${variant.fm21}); refusing to mix variants`);
      continue;
    }
    if (marks > 1) fail(`PATCH ${p.id} marker appears ${marks} times (need 0 or 1)`);
    if (marks === 1) { // already applied -> idempotent no-op, but the module must be consistent
      const want = p.survives ? 1 : 0;
      if (ms.length !== want) fail(`PATCH ${p.id} already applied but its anchor now matches ${ms.length} times (expected ${want})`);
      continue;
    }
    if (ms.length !== p.expect) fail(`ANCHOR ${p.id} matched ${ms.length} times (need exactly ${p.expect}). ${p.note}`);
    if (p.id === 'FM21-M') { ctx.toast = toastName(cur); ctx.quota = quotaName(cur); }
    const m = ms[0];
    const rep = p.build(m, ctx, variant);
    const before = cur.length;
    cur = cur.slice(0, m.index) + rep + cur.slice(m.index + m[0].length);
    added[p.id] = cur.length - before;
  }
  return { module: cur, added };
}

// ------------------------------------------------------------------ html anchors A1 / A2
function findMockBlock(html) {
  const re = /<script data-app="records"( data-puter-persist="1")?>\n([\s\S]*?)\n<\/script>/g;
  const all = [...html.matchAll(re)];
  if (all.length !== 1) fail(`ANCHOR A1 <script data-app="records">…</script> matched ${all.length} times (need exactly 1). Did kit build.mjs step 8 change?`);
  const m = all[0];
  const body = m[2];
  const isGeneric = body.includes('everything-mock:');
  const isPersist = MARK.test(body) && !!m[1];
  if (!isGeneric && !isPersist) fail(`ANCHOR A1 block is neither the generic mock (no 'everything-mock:') nor a puter-persist block; refusing to replace an unknown/own mock.`);
  return { m, isGeneric, isPersist };
}
const MODULE_RE = /<script type="module">\n([\s\S]*?)\n<\/script>/g;
const moduleScripts = (html) => [...html.matchAll(MODULE_RE)];

export function transform(html, variant, layerSrc = payloadLayer()) {
  const { m } = findMockBlock(html);
  const mods = moduleScripts(html);
  if (mods.length !== 1) fail(`ANCHOR A2 <script type="module"> matched ${mods.length} times (need exactly 1)`);
  const mm = mods[0];
  if (!(m.index < mm.index)) fail('ANCHOR order: A1 (mock block) must precede A2 (app module)');
  const { module, added } = patchModule(mm[1], variant);
  const block = `<script data-app="records" data-puter-persist="1">\n${escScript(layerSrc)}\n</script>`;
  const modStart = mm.index + '<script type="module">\n'.length;
  const out = html.slice(0, m.index) + block + html.slice(m.index + m[0].length, modStart) + module + html.slice(modStart + mm[1].length);
  transform.lastAdded = added;
  return out;
}

