  upstreamCommit: UPSTREAM.commit,
  sourceSha256: '01969d81bdca384b81c28d0fb119f44d3ba26c1b66351f343624f797579afcac',     // sha256 over (path, sha256(bytes)) of every build input; see sourceDigest()
  viteJsSha256: '352c7990c281aad0127386b537fd44ad800290403312f9f32525031b3ef537b8',         // dist/assets/*.js exactly as Vite 8.3.4 writes it
  viteCssSha256: '429e2bddae4e7fa4843b2fc94c5d7fe8436f48fe2e52926b16c10ce54df29d5d',       // dist/assets/*.css
  inputModuleSha256: '596ac669584853afe975a9a1c4e9be72b333763d5c5fefef26c135b71a050e60', // = PINS.inputModuleSha256, the original kit's module
  inputPageSha256: 'da7bfbc225f6df9011bf0123fe8f14cf7a69932c04c1d630d62847f466744a1d',    // the page this stage hands to stage 2
