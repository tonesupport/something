//   vendor/npm/*.tgz   exact npm tarballs, checked against the sha512 integrity in src/records/package-lock.json
//   src/records        the app source (pinned by STAGE1.sourceSha256)
//   kit/               page.template.html, retheme.css.tpl, fonts/*.woff2 -- the non-source parts of the page
