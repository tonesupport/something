// ------------------------------------------------------------------ build one variant
export function buildVariant(inputHtml, variantName, { quiet = false, log = console.log } = {}) {
  const v = VARIANTS[variantName] || fail(`unknown variant '${variantName}' (known: ${Object.keys(VARIANTS).join(', ')})`);
  const inMods = moduleScripts(inputHtml);
  if (inMods.length !== 1) fail(`input has ${inMods.length} module scripts`);
  const inputSha = sha(inputHtml);
  const out = transform(inputHtml, v);
  const added = { ...transform.lastAdded };
  const out2 = transform(inputHtml, v);
  if (out2 !== out) fail('determinism check failed: two transforms of the same input differ');
  const rows = verify(out, { variant: v, variantName, inputModule: inMods[0][1], inputSha });
  const idem = transform(out, v) === out;
  rows.push({ id: 'V23', desc: 'idempotence: transform(transform(x)) === transform(x)', ok: idem, detail: '' });
  rows.push({ id: 'V24', desc: 'determinism: two transforms of the same input are byte-identical', ok: out2 === out, detail: '' });
  const f = formatVerify(rows);
  if (!quiet) log(`[build-records-single ${SCRIPT_VERSION}] variant ${variantName}: ${v.note}\n${f.text}`);
  if (!f.ok) fail(`verification failed for variant ${variantName}:\n${f.text}`);
  const modOut = moduleScripts(out)[0][1];
  const manifest = {
    app: 'records', scriptVersion: SCRIPT_VERSION, variant: variantName, level: v.level, fm19: v.fm19, fm21: v.fm21,
    specs: SPEC, upstream: UPSTREAM,
    payloads: { 'persist-layer': { sha256: PAYLOAD_SHA256, bytes: PAYLOAD_BYTES, marker: 'puter-persist v1' } },
    patches: PATCHES.filter((p) => p.applies(v)).map((p) => ({ id: p.id, bytesAdded: added[p.id] ?? 0, note: p.note })),
    inputSha256: inputSha, inputModuleSha256: sha(inMods[0][1]), moduleSha256: sha(modOut),
    output: { bytes: Buffer.byteLength(out), sha256: sha(out) },
  };
  return { out, manifest, rows, verifyText: f.text };
}

