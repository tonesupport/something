const BUILD_INPUTS = [ // relative to src/records, plus one file from dev/
  'index.html', 'package.json', 'package-lock.json', 'vite.config.js', 'public', 'src',
];
const DEV_FILE = path.join('dev', 'puter-localhost.mjs');

const walkFiles = (abs, rel = '') => {
  const st = fs.statSync(abs);
  if (!st.isDirectory()) return [rel];
  return fs.readdirSync(abs).sort().flatMap((n) => walkFiles(path.join(abs, n), rel ? `${rel}/${n}` : n));
};
function buildInputFiles() {
  const out = [];
  for (const b of BUILD_INPUTS) {
    const abs = path.join(APP, b);
    if (!fs.existsSync(abs)) fail(`SOURCE build input missing: src/records/${b}`);
    for (const f of walkFiles(abs, b)) out.push({ rel: `src/records/${f}`, abs: path.join(APP, ...f.split('/')) });
  }
  out.push({ rel: 'dev/puter-localhost.mjs', abs: path.join(REPO, DEV_FILE) });
  return out.sort((a, b) => (a.rel < b.rel ? -1 : 1));
}
export function sourceDigest() {
  const h = createHash('sha256');
  for (const f of buildInputFiles()) h.update(`${f.rel}\0${sha(fs.readFileSync(f.abs))}\n`);
  return h.digest('hex');
}

// ---- minimal .tgz reader (gzip + ustar/pax/GNU long names); enough for npm tarballs
export function untar(tgz, destDir) {
  const buf = zlib.gunzipSync(tgz);
  const str = (o, n) => { const e = buf.indexOf(0, o); return buf.toString('utf8', o, e < 0 || e > o + n ? o + n : e); };
  let pos = 0, longName = null, pax = {};
  while (pos + 512 <= buf.length) {
    if (buf.subarray(pos, pos + 512).every((b) => b === 0)) break;
    let name = str(pos, 100);
    const size = parseInt(str(pos + 124, 12).trim() || '0', 8);
    const type = String.fromCharCode(buf[pos + 156] || 48);
    const mode = parseInt(str(pos + 100, 8).trim() || '0', 8);
    if (str(pos + 257, 5) === 'ustar') { const pre = str(pos + 345, 155); if (pre) name = `${pre}/${name}`; }
    const body = buf.subarray(pos + 512, pos + 512 + size);
    pos += 512 + Math.ceil(size / 512) * 512;
    if (type === 'x') { for (const m of body.toString('utf8').matchAll(/\d+ ([^=]+)=([^\n]*)\n/g)) pax[m[1]] = m[2]; continue; }
    if (type === 'g') continue;
    if (type === 'L') { longName = body.toString('utf8').replace(/\0.*$/s, ''); continue; }
    if (pax.path) name = pax.path;
    if (longName) name = longName;
    pax = {}; longName = null;
    const parts = name.split('/').slice(1); // drop the leading "package/"
    if (!parts.length || parts.some((p) => p === '..' || p === '')) { if (type === '5' && parts.length === 0) continue; fail(`TAR unsafe or empty path "${name}"`); }
    const dest = path.join(destDir, ...parts);
    if (type === '5') { fs.mkdirSync(dest, { recursive: true }); continue; }
    if (type !== '0') continue; // links and devices are not used by the vendored packages
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, body, { mode: mode & 0o111 ? 0o755 : 0o644 });
  }
}

// ---- which locked packages does `vite build` need on THIS machine?
function libc() {
  if (process.platform !== 'linux') return null;
  try { return process.report.getReport().header.glibcVersionRuntime ? 'glibc' : 'musl'; } catch { return 'glibc'; }
}
function platformOk(v) {
  if (v.os && !v.os.includes(process.platform)) return false;
  if (v.cpu && !v.cpu.includes(process.arch)) return false;
  if (v.libc && !v.libc.includes(libc())) return false;
  return true;
}
export function lockClosure(lockPackages, roots = ['node_modules/vite', 'node_modules/lucide']) {
  const resolve = (from, dep) => {
    let p = from;
    for (;;) {
      const k = `${p ? p + '/' : ''}node_modules/${dep}`;
      if (lockPackages[k]) return k;
      if (!p) return null;
      const i = p.lastIndexOf('/node_modules/');
      p = i < 0 ? '' : p.slice(0, i);
    }
  };
  const need = new Map();
  const walk = (k, optional) => {
    const v = lockPackages[k];
    if (!v || need.has(k)) return;
    if (optional && !platformOk(v)) return;
    need.set(k, v);
    for (const d of Object.keys(v.dependencies || {})) { const r = resolve(k, d); if (r) walk(r, false); }
    for (const d of Object.keys(v.optionalDependencies || {})) { const r = resolve(k, d); if (r) walk(r, true); }
    for (const d of Object.keys(v.peerDependencies || {})) { if (v.peerDependenciesMeta?.[d]?.optional) continue; const r = resolve(k, d); if (r) walk(r, false); }
  };
  for (const r of roots) walk(r, false);
  return need;
}
const tarballName = (key, v) => `${key.replace(/^.*node_modules\//, '').replace('/', '__')}-${v.version}.tgz`;

function installVendored(stageApp, log) {
  const lock = JSON.parse(fs.readFileSync(path.join(APP, 'package-lock.json'), 'utf8')).packages;
  const need = lockClosure(lock);
  let bytes = 0;
  for (const [key, v] of need) {
    const f = path.join(VENDOR, tarballName(key, v));
    if (!fs.existsSync(f)) fail(`VENDOR missing ${path.relative(REPO, f)} (needed on ${process.platform}/${process.arch}${libc() ? '/' + libc() : ''}). Add that exact tarball from ${v.resolved}; its integrity is checked against package-lock.json.`);
    const b = fs.readFileSync(f);
    const got = 'sha512-' + createHash('sha512').update(b).digest('base64');
    if (got !== v.integrity) fail(`VENDOR integrity mismatch for ${path.basename(f)}: lockfile says ${v.integrity.slice(0, 24)}... file is ${got.slice(0, 24)}...`);
    untar(b, path.join(stageApp, key));
    bytes += b.length;
  }
  log(`  vendored toolchain: ${need.size} packages unpacked and verified against package-lock.json (${(bytes / 1e6).toFixed(1)} MB of tarballs)`);
}

function runVite(stageApp, log) {
  const vite = path.join(stageApp, 'node_modules', 'vite', 'bin', 'vite.js');
  const env = { PATH: process.env.PATH || '', HOME: stageApp, TMPDIR: os.tmpdir(), TEMP: os.tmpdir(), TMP: os.tmpdir(), SystemRoot: process.env.SystemRoot || '' };
  const r = spawnSync(process.execPath, [vite, 'build', '--logLevel', 'warn'], { cwd: stageApp, env, encoding: 'utf8' });
  if (r.status !== 0) fail(`VITE build failed (exit ${r.status}):\n${r.stdout}${r.stderr}`);
  if (r.stdout.trim() || r.stderr.trim()) log(`  vite said: ${(r.stdout + r.stderr).trim().split('\n').slice(0, 5).join(' / ')}`);
  const dist = path.join(stageApp, 'dist');
  const one = (ext) => { const m = fs.readdirSync(path.join(dist, 'assets')).filter((n) => n.endsWith(ext)); if (m.length !== 1) fail(`VITE expected exactly one dist/assets/*${ext}, found ${m.length}`); return path.join(dist, 'assets', m[0]); };
  return { dist, js: fs.readFileSync(one('.js'), 'utf8'), css: fs.readFileSync(one('.css'), 'utf8') };
}

const expectPin = (what, got, want) => { if (got !== want) fail(`PIN ${what}: expected ${want} but got ${got}`); };

// ---- stage 1: returns the input page for stage 2, plus a record of what happened
export function stage1({ log = console.log, keepTmp = false } = {}) {
  const [maj, min] = process.versions.node.split('.').map(Number);
  if (maj < 22 || (maj === 22 && min < 12)) fail(`NODE ${process.versions.node} is too old; need ${STAGE1.node}`);
  const src = sourceDigest();
  expectPin('source (src/records build inputs + dev/puter-localhost.mjs; did autocrlf rewrite line endings?)', src, STAGE1.sourceSha256);
  log(`  source pinned: ${src.slice(0, 16)}... (${buildInputFiles().length} files)`);
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'records-build-'));
  try {
    const stageApp = path.join(tmp, 'src', 'records');
    fs.mkdirSync(stageApp, { recursive: true });
    for (const f of buildInputFiles()) { const d = path.join(tmp, ...f.rel.split('/')); fs.mkdirSync(path.dirname(d), { recursive: true }); fs.copyFileSync(f.abs, d); }
    installVendored(stageApp, log);
    const v = runVite(stageApp, log);
    expectPin('vite js', sha(v.js), STAGE1.viteJsSha256);
    expectPin('vite css', sha(v.css), STAGE1.viteCssSha256);
    log(`  vite 8.3.4 output reproduced: js ${sha(v.js).slice(0, 16)}... css ${sha(v.css).slice(0, 16)}...`);
    // the kit's retheme block: fonts + palette, inserted before the FIRST "</head>" in the bundle text.
    // (That first occurrence is inside the print-preview HTML string in the app, not the page head. The pinned
    //  original did exactly this, so this is reproduced as-is. See README.)
    let tpl = fs.readFileSync(path.join(KIT, 'retheme.css.tpl'), 'utf8');
    tpl = tpl.replace(/@@font:([^@]+)@@/g, (_, n) => fs.readFileSync(path.join(KIT, 'fonts', n)).toString('base64'));
    const at = v.js.indexOf('</head>');
    if (at < 0) fail('KIT no "</head>" in the Vite bundle to anchor the retheme block');
    const mod = escScript(v.js.slice(0, at) + tpl + v.js.slice(at));
    expectPin('input module', sha(mod), STAGE1.inputModuleSha256);
    let page = fs.readFileSync(path.join(KIT, 'page.template.html'), 'utf8');
    const fill = { module: mod, css: v.css };
    page = page.replace(/@@icon:([^@]+)@@/g, (_, n) => {
      const mime = n.endsWith('.ico') ? 'image/x-icon' : 'image/png';
      return `data:${mime};base64,${fs.readFileSync(path.join(v.dist, n)).toString('base64')}`;
    }).replace(/@@(module|css)@@/g, (_, k) => fill[k]);
    if (/@@(module|css|icon|font)/.test(page.replace(mod, '').replace(v.css, ''))) fail('KIT unfilled placeholder left in the page');
    expectPin('input page', sha(page), STAGE1.inputPageSha256);
    log(`  input page assembled: ${Buffer.byteLength(page)} bytes sha256=${sha(page).slice(0, 16)}...`);
    return page;
  } finally {
    if (keepTmp) log(`  (kept ${tmp})`); else fs.rmSync(tmp, { recursive: true, force: true });
  }
}

// ------------------------------------------------------------------ CLI (merged: stage 1 + stage 2)
function cli(argv) {
  const opt = (name, dflt) => { const i = argv.indexOf('--' + name); return i >= 0 ? argv[i + 1] : dflt; };
  const has = (name) => argv.includes('--' + name);
  if (has('help') || has('h')) {
    console.log(`build.mjs -- records.html from pinned source, offline, one command.

  node standalone/records/build.mjs                    source -> out/records.html (variant ${DEFAULT_VARIANT})
  node standalone/records/build.mjs --out FILE         write somewhere else (a FILE.build.json manifest is written beside it)
  node standalone/records/build.mjs --variant NAME     one of: ${Object.keys(VARIANTS).join(', ')}
  node standalone/records/build.mjs --all --outdir DIR build every variant
  node standalone/records/build.mjs --stage1-only      write out/records.input.html and stop
  node standalone/records/build.mjs --from-html IN     skip stage 1; run stage 2 on a page you supply
  node standalone/records/build.mjs --selftest         stage-2 self-test (synthetic pages + the stage-1 page)
  node standalone/records/build.mjs --keep-tmp         keep the temp build dir for inspection
exit 0 ok; exit 1 BuildError (the message names the pin, anchor or check that failed).`);
    return;
  }
  if (has('print-manifest')) {
    console.log(JSON.stringify({ scriptVersion: SCRIPT_VERSION, upstream: UPSTREAM, stage1: STAGE1, payload: { sha256: PAYLOAD_SHA256, bytes: PAYLOAD_BYTES }, pins: PINS, originalInputSha256: ORIGINAL_INPUT_SHA256, variants: VARIANTS, defaultVariant: DEFAULT_VARIANT }, null, 2));
    return;
  }
  const log = console.log;
  const keepTmp = has('keep-tmp');
  const outDir = path.join(HERE, 'out');
  const getInput = () => {
    if (opt('from-html')) { log('[build] stage 1 skipped (--from-html)'); return fs.readFileSync(path.resolve(opt('from-html')), 'utf8'); }
    log('[build] stage 1: source -> input page');
    return stage1({ log, keepTmp });
  };
  if (has('stage1-only')) {
    const page = getInput(); fs.mkdirSync(outDir, { recursive: true });
    const f = path.join(outDir, 'records.input.html'); fs.writeFileSync(f, page); log(`[build] wrote ${f} sha256=${sha(page)}`); return;
  }
  if (has('selftest')) { selftest(getInput()); return; }
  const html = getInput();
  log('[build] stage 2: input page -> records.html');
  const write = (vn, f) => {
    const r = buildVariant(html, vn, { log: (m) => log(m.split('\n').filter((l, i) => i === 0 || /FAIL|verify\(\)/.test(l)).join('\n')) });
    fs.mkdirSync(path.dirname(f), { recursive: true });
    fs.writeFileSync(f, r.out);
    fs.writeFileSync(f.replace(/\.html$/, '.build.json'), JSON.stringify({ ...r.manifest, stage1: STAGE1 }, null, 2) + '\n');
    const pin = PINS.outputs[vn];
    log(`[build] OK ${f} (${r.manifest.output.bytes} bytes) sha256=${r.manifest.output.sha256}${pin && pin.sha256 === r.manifest.output.sha256 ? '  == frozen pin' : '  (NO frozen pin to compare)'}`);
  };
  if (has('all')) { const d = path.resolve(opt('outdir', outDir)); for (const vn of Object.keys(VARIANTS)) write(vn, path.join(d, `records-${vn}.html`)); return; }
  const vn = opt('variant', DEFAULT_VARIANT);
  write(vn, path.resolve(opt('out', path.join(outDir, 'records.html'))));
}
const isMain = process.argv[1] && fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url));
if (isMain) {
  try { cli(process.argv.slice(2)); }
  catch (e) { console.error('[build] FAILED: ' + (e instanceof BuildError ? e.message : e.stack || e)); process.exit(1); }
}
